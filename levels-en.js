  function normalizeLevel(value) {
    return LEVEL_KEYS.indexOf(value) >= 0 ? value : "learner";
  }

  function pick(entry, level) {
    if (!entry) return null;
    var key = normalizeLevel(level);
    return entry[key] || entry.learner || entry.beginner || entry.pro || null;
  }

  function getPath(target, dotted) {
    var node = target;
    var parts = String(dotted || "").split(".");
    for (var i = 0; i < parts.length; i += 1) {
      if (node == null) return null;
      node = node[parts[i]];
    }
    return node;
  }

  function fill(text, vars) {
    if (text == null) return "";
    var out = String(text);
    if (!vars) return out;
    Object.keys(vars).forEach(function (key) {
      out = out.split("{" + key + "}").join(String(vars[key]));
    });
    return out;
  }

  var textCache = new Map();

  function ui(dotted, level, vars) {
    var cacheKey = dotted + "|" + normalizeLevel(level);
    var value = textCache.get(cacheKey);
    if (value === undefined) {
      var node = getPath(CORE.ui, dotted);
      value = pick(node, level) || "";
      textCache.set(cacheKey, value);
    }
    return fill(value, vars);
  }

  function levelMeta(level) {
    return LEVELS[normalizeLevel(level)] || LEVELS.learner;
  }

  function chordText(id, level) {
    return pick(CHORDS[id], level) || { summary: "", use: "", tip: "" };
  }

  function modeText(id, level) {
    return pick(MODES[id], level) || { mood: "", use: "", improv: "" };
  }

  function intervalText(code, level) {
    return pick(CORE.intervals[code], level) || { sound: "", use: "" };
  }

  function degreeText(degree, level) {
    var entry = pick(CORE.degrees[String(degree)], level);
    return entry ? entry.hint || "" : "";
  }

  function voicingText(key, level) {
    return pick(CORE.voicings[key], level) || "";
  }

  function progressionNote(index, level) {
    return pick(CORE.progressionNotes[String(index)], level) || "";
  }

  function knowledgeText(key, level) {
    return pick(CORE.knowledge[key], level) || { body: "", points: [] };
  }

  function historyIntro(level) {
    return pick(CORE.historyIntro, level) || "";
  }

  function levelCss(level) {
    return "lvl-" + normalizeLevel(level);
  }

