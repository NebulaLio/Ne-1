const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const readJson = (p, fallback) => {
  try {
    return JSON.parse(fs.readFileSync(path.join(root, p), "utf8"));
  } catch (err) {
    console.warn(`[build-levels] skip ${p}: ${err.message}`);
    return fallback;
  }
};

const core = readJson("content/core.json", null);
const data = readJson("tools/data.json", { chords: [], modes: [] });
const chords = readJson("content/chords.json", {});
const modes = readJson("content/modes.json", {});
if (!core) throw new Error("content/core.json is required");

const LEVELS = ["beginner", "learner", "pro"];
const missing = { chords: [], modes: [] };
const fallbackChord = (c) => ({
  beginner: { summary: c.theory || "", use: c.function || "", tip: c.guitar || "" },
  learner: { summary: c.theory || "", use: c.function || "", tip: c.guitar || "" },
  pro: { summary: c.theory || "", use: c.function || "", tip: c.guitar || "" },
});
const fallbackMode = (m) => ({
  beginner: { mood: m.feature || "", use: m.progression || "", improv: m.improv || "" },
  learner: { mood: m.feature || "", use: m.progression || "", improv: m.improv || "" },
  pro: { mood: m.feature || "", use: m.progression || "", improv: m.improv || "" },
});

const chordOut = {};
for (const c of data.chords) {
  const entry = chords[c.id];
  if (!entry) missing.chords.push(c.id);
  chordOut[c.id] = entry || fallbackChord(c);
}
const modeOut = {};
for (const m of data.modes) {
  const entry = modes[m.id];
  if (!entry) missing.modes.push(m.id);
  modeOut[m.id] = entry || fallbackMode(m);
}

// validate shape
const problems = [];
for (const [id, entry] of Object.entries(chordOut)) {
  for (const lv of LEVELS) {
    const item = entry[lv];
    if (!item || !item.summary || !item.use || !item.tip) problems.push(`chord ${id}/${lv} incomplete`);
  }
}
for (const [id, entry] of Object.entries(modeOut)) {
  for (const lv of LEVELS) {
    const item = entry[lv];
    if (!item || !item.mood || !item.use || !item.improv) problems.push(`mode ${id}/${lv} incomplete`);
  }
}

const banner = `/* ============================================================
   Nebula · 三档解说文本系统 (generated by tools/build-levels.js)
   beginner 初学者 / learner 学过乐理 / pro 音乐人
   文案源文件：content/core.json + content/chords.json + content/modes.json
   ============================================================ */
`;
const body = `${banner}(function () {
  "use strict";

  var LEVEL_KEYS = ["beginner", "learner", "pro"];

  var LEVELS = ${JSON.stringify(core.levels, null, 2)};

  var CORE = ${JSON.stringify(core, null, 2)};

  var CHORDS = ${JSON.stringify(chordOut, null, 2)};

  var MODES = ${JSON.stringify(modeOut, null, 2)};

  function normalizeLevel(value) {
    return LEVEL_KEYS.indexOf(value) >= 0 ? value : "learner";
  }

  function pick(entry, level) {
    if (!entry) return null;
    var key = normalizeLevel(level);
    return entry[key] || entry.learner || entry.beginner || entry.pro || null;
  }

  function getPath(target, dotted) {
    var node = target;
    var parts = String(dotted || "").split(".");
    for (var i = 0; i < parts.length; i += 1) {
      if (node == null) return null;
      node = node[parts[i]];
    }
    return node;
  }

  function fill(text, vars) {
    if (text == null) return "";
    var out = String(text);
    if (!vars) return out;
    Object.keys(vars).forEach(function (key) {
      out = out.split("{" + key + "}").join(String(vars[key]));
    });
    return out;
  }

  var textCache = new Map();

  function ui(dotted, level, vars) {
    var cacheKey = dotted + "|" + normalizeLevel(level);
    var value = textCache.get(cacheKey);
    if (value === undefined) {
      var node = getPath(CORE.ui, dotted);
      value = pick(node, level) || "";
      textCache.set(cacheKey, value);
    }
    return fill(value, vars);
  }

  function levelMeta(level) {
    return LEVELS[normalizeLevel(level)] || LEVELS.learner;
  }

  function chordText(id, level) {
    return pick(CHORDS[id], level) || { summary: "", use: "", tip: "" };
  }

  function modeText(id, level) {
    return pick(MODES[id], level) || { mood: "", use: "", improv: "" };
  }

  function intervalText(code, level) {
    return pick(CORE.intervals[code], level) || { sound: "", use: "" };
  }

  function degreeText(degree, level) {
    var entry = pick(CORE.degrees[String(degree)], level);
    return entry ? entry.hint || "" : "";
  }

  function voicingText(key, level) {
    return pick(CORE.voicings[key], level) || "";
  }

  function progressionNote(index, level) {
    return pick(CORE.progressionNotes[String(index)], level) || "";
  }

  function knowledgeText(key, level) {
    return pick(CORE.knowledge[key], level) || { body: "", points: [] };
  }

  function historyIntro(level) {
    return pick(CORE.historyIntro, level) || "";
  }

  function levelCss(level) {
    return "lvl-" + normalizeLevel(level);
  }

  window.NBL = {
    LEVEL_KEYS: LEVEL_KEYS,
    LEVELS: LEVELS,
    ui: ui,
    levelMeta: levelMeta,
    chordText: chordText,
    modeText: modeText,
    intervalText: intervalText,
    degreeText: degreeText,
    voicingText: voicingText,
    progressionNote: progressionNote,
    knowledgeText: knowledgeText,
    historyIntro: historyIntro,
    levelCss: levelCss,
    normalizeLevel: normalizeLevel,
    _data: { chords: CHORDS, modes: MODES, core: CORE }
  };
})();
`;

fs.writeFileSync(path.join(root, "levels.js"), body, "utf8");
console.log(`[build-levels] wrote levels.js (${(body.length / 1024).toFixed(1)} KB)`);
if (missing.chords.length) console.warn(`[build-levels] fallback chords (${missing.chords.length}): ${missing.chords.join(", ")}`);
if (missing.modes.length) console.warn(`[build-levels] fallback modes (${missing.modes.length}): ${missing.modes.join(", ")}`);
if (problems.length) {
  console.warn(`[build-levels] ${problems.length} incomplete entries`);
  problems.slice(0, 12).forEach((p) => console.warn("  - " + p));
  process.exitCode = 1;
}
